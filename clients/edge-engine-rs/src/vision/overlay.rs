#[inline(always)]
fn get_char_bitmap(c: char) -> &'static [u8] {
    let code = c as usize;
    if (32..=126).contains(&code) {
        let idx = (code - 32) * 8;
        &FONT_8X8[idx..idx + 8]
    } else {
        // Fallback karakter spasi
        &FONT_8X8[0..8]
    }
}

/// Gambar string ASCII ke buffer RGB8 dengan kotak latar belakang opsional
#[allow(clippy::too_many_arguments)]
pub fn draw_text(
    rgb: &mut [u8],
    width: usize,
    height: usize,
    x: i32,
    y: i32,
    text: &str,
    color: (u8, u8, u8),
    bg: Option<(u8, u8, u8)>,
) {
    let len = text.len();
    if len == 0 {
        return;
    }

    let text_w = len * FONT_WIDTH;
    let text_h = FONT_HEIGHT;

    // Gambar kotak latar belakang jika diminta
    if let Some(bg_color) = bg {
        let pad = 2;
        let x0 = (x - pad).clamp(0, width as i32 - 1) as usize;
        let y0 = (y - pad).clamp(0, height as i32 - 1) as usize;
        let x1 = (x + text_w as i32 + pad).clamp(0, width as i32 - 1) as usize;
        let y1 = (y + text_h as i32 + pad).clamp(0, height as i32 - 1) as usize;

        for py in y0..=y1 {
            for px in x0..=x1 {
                let idx = (py * width + px) * 3;
                if idx + 2 < rgb.len() {
                    rgb[idx] = bg_color.0;
                    rgb[idx + 1] = bg_color.1;
                    rgb[idx + 2] = bg_color.2;
                }
            }
        }
    }

    // Render karakter
    for (i, c) in text.chars().enumerate() {
        let char_x = x + (i * FONT_WIDTH) as i32;
        if char_x + 8 <= 0 || char_x >= width as i32 {
            continue;
        }

        let glyph = get_char_bitmap(c);
        for (row, &byte) in glyph.iter().enumerate().take(8) {
            let py = y + row as i32;
            if py < 0 || py >= height as i32 {
                continue;
            }
            for col in 0..8 {
                if (byte & (0x80 >> col)) != 0 {
                    let px = char_x + col;
                    if px >= 0 && px < width as i32 {
                        let idx = (py as usize * width + px as usize) * 3;
                        if idx + 2 < rgb.len() {
                            rgb[idx] = color.0;
                            rgb[idx + 1] = color.1;
                            rgb[idx + 2] = color.2;
                        }
                    }
                }
            }
        }
    }
}

/// Gambar kotak persegi panjang dengan ketebalan yang dapat diatur
pub fn draw_rect(
    rgb: &mut [u8],
    width: usize,
    height: usize,
    bbox: &[i32; 4],
    color: (u8, u8, u8),
    thickness: usize,
) {
    let [x, y, w, h] = *bbox;
    let x0 = x.clamp(0, width as i32 - 1) as usize;
    let y0 = y.clamp(0, height as i32 - 1) as usize;
    let x1 = (x + w).clamp(0, width as i32 - 1) as usize;
    let y1 = (y + h).clamp(0, height as i32 - 1) as usize;

    if x1 <= x0 || y1 <= y0 {
        return;
    }

    for t in 0..thickness {
        let yt = (y0 + t).min(height - 1);
        let yb = y1.saturating_sub(t);
        for px in x0..=x1 {
            let it = (yt * width + px) * 3;
            if it + 2 < rgb.len() {
                rgb[it] = color.0;
                rgb[it + 1] = color.1;
                rgb[it + 2] = color.2;
            }
            let ib = (yb * width + px) * 3;
            if ib + 2 < rgb.len() {
                rgb[ib] = color.0;
                rgb[ib + 1] = color.1;
                rgb[ib + 2] = color.2;
            }
        }
        let xl = (x0 + t).min(width - 1);
        let xr = x1.saturating_sub(t);
        for py in y0..=y1 {
            let il = (py * width + xl) * 3;
            if il + 2 < rgb.len() {
                rgb[il] = color.0;
                rgb[il + 1] = color.1;
                rgb[il + 2] = color.2;
            }
            let ir = (py * width + xr) * 3;
            if ir + 2 < rgb.len() {
                rgb[ir] = color.0;
                rgb[ir + 1] = color.1;
                rgb[ir + 2] = color.2;
            }
        }
    }
}

/// Parse string warna hex (misalnya "#22c55e" atau "22c55e") menjadi RGB (r, g, b)
pub fn parse_hex_color(hex: &str) -> (u8, u8, u8) {
    let s = hex.trim_start_matches('#');
    if s.len() == 6 {
        if let (Ok(r), Ok(g), Ok(b)) = (
            u8::from_str_radix(&s[0..2], 16),
            u8::from_str_radix(&s[2..4], 16),
            u8::from_str_radix(&s[4..6], 16),
        ) {
            return (r, g, b);
        }
    }
    (0, 255, 0)
}
